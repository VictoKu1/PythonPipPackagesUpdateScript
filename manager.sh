#!/bin/bash

# Python Pip Packages Update Script Manager
# Manages installation and removal of the updatePip command
# Author: Original + Improvements
# Version: 2.0

set -euo pipefail  # Exit on error, undefined vars, pipe failures

# Configuration
readonly SCRIPT_NAME="manager.sh"
readonly COMMAND_NAME="updatePip"
readonly COMMAND_PATH="/usr/local/bin/$COMMAND_NAME"
readonly SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
readonly UPDATE_SCRIPT="$SCRIPT_DIR/update.sh"

# Colors for output
readonly RED='\033[0;31m'
readonly GREEN='\033[0;32m'
readonly YELLOW='\033[1;33m'
readonly BLUE='\033[0;34m'
readonly NC='\033[0m' # No Color

# Logging function
log() {
    local level="$1"
    shift
    local message="$*"
    local timestamp=$(date '+%Y-%m-%d %H:%M:%S')
    echo "[$timestamp] [$level] $message"
}

# Error handling
error_exit() {
    log "ERROR" "$1"
    echo -e "${RED}Error: $1${NC}" >&2
    exit 1
}

# Success message
success() {
    echo -e "${GREEN}$1${NC}"
    log "INFO" "$1"
}

# Warning message
warning() {
    echo -e "${YELLOW}Warning: $1${NC}"
    log "WARNING" "$1"
}

# Info message
info() {
    echo -e "${BLUE}$1${NC}"
    log "INFO" "$1"
}

# Check if running as root
check_root() {
    if [ "$(id -u)" != "0" ]; then
        error_exit "This script must be run as root (use sudo)"
    fi
}

# Check if update script exists
check_update_script() {
    if [ ! -f "$UPDATE_SCRIPT" ]; then
        error_exit "Update script not found: $UPDATE_SCRIPT"
    fi
    
    if [ ! -x "$UPDATE_SCRIPT" ]; then
        warning "Update script is not executable, making it executable..."
        chmod +x "$UPDATE_SCRIPT"
    fi
}

# Install the command
install_command() {
    info "Installing $COMMAND_NAME command..."
    
    # Create the command file
    cat > "$COMMAND_PATH" << EOF
#!/bin/bash
# Python Pip Packages Update Script
# Auto-generated by manager.sh
# Do not edit manually

# Change to script directory and run update script
cd "$SCRIPT_DIR" && exec "$UPDATE_SCRIPT" "\$@"
EOF
    
    # Make it executable
    chmod +x "$COMMAND_PATH"
    
    # Verify installation
    if [ -x "$COMMAND_PATH" ]; then
        success "Successfully installed $COMMAND_NAME command to $COMMAND_PATH"
        info "You can now use '$COMMAND_NAME' from anywhere in your system"
    else
        error_exit "Failed to install $COMMAND_NAME command"
    fi
}

# Remove the command
remove_command() {
    info "Removing $COMMAND_NAME command..."
    
    if [ -f "$COMMAND_PATH" ]; then
        rm -f "$COMMAND_PATH"
        success "Successfully removed $COMMAND_NAME command"
    else
        warning "Command $COMMAND_NAME was not found at $COMMAND_PATH"
    fi
    
    # Clean up any leftover requirements files
    if [ -f "requirements.txt" ]; then
        rm -f requirements.txt
        info "Cleaned up requirements.txt"
    fi
}

# Show usage
show_usage() {
    echo "Usage: $0 [install|remove]"
    echo
    echo "Options:"
    echo "  install  - Install the updatePip command system-wide"
    echo "  remove   - Remove the updatePip command"
    echo
    echo "Examples:"
    echo "  sudo $0 install"
    echo "  sudo $0 remove"
}

# Interactive menu
show_menu() {
    echo "=========================================="
    echo "    Python Pip Packages Update Manager"
    echo "=========================================="
    echo
    echo "What would you like to do?"
    echo "1. Install updatePip command (system-wide)"
    echo "2. Remove updatePip command"
    echo "3. Exit"
    echo
}

# Get user choice
get_user_choice() {
    local choice
    read -p "Enter your choice [1-3]: " choice
    echo "$choice"
}

# Main function
main() {
    # Check if running as root
    check_root
    
    # Check if update script exists
    check_update_script
    
    # Handle command line arguments
    if [ $# -gt 0 ]; then
        case "$1" in
            install)
                install_command
                ;;
            remove)
                remove_command
                ;;
            *)
                error_exit "Invalid option: $1"
                ;;
        esac
        exit 0
    fi
    
    # Interactive mode
    while true; do
        show_menu
        choice=$(get_user_choice)
        
        case "$choice" in
            1)
                install_command
                break
                ;;
            2)
                remove_command
                break
                ;;
            3)
                info "Exiting..."
                break
                ;;
            *)
                echo -e "${RED}Invalid choice. Please enter 1, 2, or 3.${NC}"
                ;;
        esac
    done
}

# Run main function
main "$@"